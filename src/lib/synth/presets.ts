import { DEFAULT_PARAMS, type SynthParams } from "./engine";

export type FactoryPatch = {
  id: string;
  name: string;
  description: string;
  params: SynthParams;
};

function makePreset(
  id: string,
  name: string,
  description: string,
  overrides: Partial<SynthParams>,
): FactoryPatch {
  return {
    id,
    name,
    description,
    params: { ...DEFAULT_PARAMS, ...overrides },
  };
}

